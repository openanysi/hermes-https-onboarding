"""User-owned setup steps; never print a credential or run as another account."""
import argparse
import json
import os
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
import common
import hermes_api


def seller_variable(environment):
    if environment not in ("prod", "dev"):
        raise common.Failure("Choose prod or dev explicitly.")
    return "OPENANY_DEV_SELLER_KEY" if environment == "dev" else "OPENANY_SELLER_KEY"


def validate_seller(key):
    if not isinstance(key, str) or not re.fullmatch(r"[!-~]{1,4096}", key) or "${" in key:
        raise common.Failure("Seller Key must be a nonempty literal token without whitespace or interpolation. It cannot be generated by this installer.")
    return key


def read_environment(path):
    values = {}
    for line in common.regular_file(path).read_text().splitlines():
        if line and not line.startswith("#"):
            name, value = line.split("=", 1)
            values[name] = json.loads(value)
    return values


def check_environment(home, environment):
    marker = common.regular_file(Path(home) / '.openany-provider/delivery-environment')
    if marker.exists() and marker.read_text().strip() != environment:
        raise common.Failure('This Hermes home has delivery bound to another environment. Reconcile its tasks or use an isolated home before switching environments.')


def configure(home, port, environment, seller_key):
    home = hermes_api.validate_home(home)
    check_environment(home, environment)
    seller_key = validate_seller(seller_key)
    name = seller_variable(environment)
    private = common.private_directory(home / ".openany-provider")
    tasks = common.private_directory(private / "tasks")
    task_root = common.private_directory(tasks / environment)
    env_file = common.regular_file(private / (environment + ".env"))
    values = {name: seller_key, "OPENANY_TASK_ROOT": str(task_root)}
    body = "".join(key + "=" + json.dumps(value, ensure_ascii=False) + "\n" for key, value in values.items()).encode()
    changed = not env_file.exists() or env_file.read_bytes() != body or bool(env_file.stat().st_mode & 0o077)
    api = hermes_api.configure_api(home, port, True)
    try:
        with common.Transaction(private / "backups") as tx:
            if changed:
                tx.write(env_file, body)
    except BaseException:
        if api.get("backup"):
            common.restore_snapshot(Path(api["backup"]), {home / ".env", home / "config.yaml", home / "openany-api.key"})
        raise
    return {"api": api, "api_key_file": str(home / "openany-api.key"), "seller_env_file": str(env_file), "seller_changed": bool(changed), "seller_backup": str(tx.directory) if tx.directory else None, "task_root": str(task_root), "seller_variable": name, "seller_key_remote_verified": False}


def environment_file_line(env_file):
    value = str(env_file)
    if not Path(value).is_absolute() or any(ord(char) < 32 for char in value) or any(char in value for char in '*?[]'):
        raise common.Failure("Invalid environment file path.")
    # Unlike ExecStart/Environment, systemd's EnvironmentFile parser consumes
    # the entire literal path. Surrounding quotes become part of that path.
    return 'EnvironmentFile=' + value.replace('%', '%%') + '\n'


def dropin_text(env_file):
    return '# Managed by OpenAny Hermes one-click setup\n[Service]\n' + environment_file_line(env_file)


def write_user_dropin(home, unit, environment):
    if not re.fullmatch(r"hermes-gateway(?:-[A-Za-z0-9_-]+)?\.service", unit):
        raise common.Failure("Unexpected Gateway unit name.")
    directory = Path.home() / ".config/systemd/user" / (unit + ".d")
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = common.regular_file(directory / "openany-provider.conf")
    body = dropin_text(home / ".openany-provider" / (environment + ".env")).encode()
    if path.exists() and not path.read_text().startswith("# Managed by OpenAny Hermes one-click setup"):
        raise common.Failure("An unmanaged Gateway environment drop-in already exists.")
    changed = not path.exists() or path.read_bytes() != body
    with common.Transaction(home / ".openany-provider/backups") as tx:
        if changed:
            tx.write(path, body, 0o644)
    return {"changed": changed, "path": str(path), "backup": str(tx.directory) if tx.directory else None}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("configure", "dropin", "progress", "marker", "delivery", "listing"))
    parser.add_argument("--home", type=Path, required=True)
    parser.add_argument("--environment", choices=("prod", "dev"), default="prod")
    parser.add_argument("--port", type=int, default=8642)
    parser.add_argument("--unit")
    args = parser.parse_args()
    try:
        home = hermes_api.validate_home(args.home)
        payload = json.load(sys.stdin)
        if args.action == "configure":
            result = configure(home, args.port, args.environment, payload.get("seller_key", ""))
        elif args.action == "dropin":
            result = write_user_dropin(home, args.unit or "", args.environment)
        elif args.action == "delivery":
            import cli_delivery
            result = cli_delivery.configure(home, args.environment, args.port, payload["relay_port"], payload["node_bin"], payload["cli_bin"])
        elif args.action == "listing":
            import cli_delivery
            reference = cli_delivery.listing(payload["domain"], args.environment, payload["skills"], payload.get("files_required", False))
            path = common.private_directory(home / ".openany-provider") / "listing-reference.json"
            common.atomic_write(path, json.dumps(reference, indent=2).encode())
            result = {"path": str(path), "skill_count": len(reference["skills"]), "base_url": reference["base_url"], "upstream_path": reference["upstream_path"]}
        else:
            private = common.private_directory(home / ".openany-provider")
            if args.action == "marker":
                fingerprint = payload.get("fingerprint", "")
                if not re.fullmatch(r"[a-f0-9]{64}", fingerprint):
                    raise common.Failure("Invalid runtime fingerprint.")
                common.atomic_write(private / ("runtime-" + args.environment + ".json"), json.dumps(payload).encode())
            else:
                job = payload.get("job_id", "")
                if not re.fullmatch(r"[a-f0-9]{24}", job):
                    raise common.Failure("Invalid job identity.")
                directory = common.private_directory(private / "setup-jobs")
                data = json.dumps(payload, indent=2).encode()
                common.atomic_write(directory / (job + ".json"), data)
                common.atomic_write(directory / "latest.json", data)
            result = {"saved": True}
    except common.Failure as error:
        print(json.dumps({"ok": False, "error": str(error)}))
        return 1
    except Exception:
        print(json.dumps({"ok": False, "error": "User configuration failed; no credential values were printed."}))
        return 1
    print(json.dumps({"ok": True, **result}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
